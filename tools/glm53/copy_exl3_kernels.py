#!/usr/bin/env python3
"""Device-only copies of GLM-5.3's EXL3 CUDA kernels for the Zig build (nvcc -fatbin, no ATen, no torch).

From the Python engine's src/tensorfold/cuda/exl3/{linear.cu, experts.cu, experts_grouped.cuh, decode.cuh}:

* zig/kernels/cuda/glm53/decode.cuh            verbatim (it has no ATen)
* zig/kernels/cuda/glm53/experts_grouped.cuh   the device part (ATen includes, launch_ex and the host launchers cut)
* zig/kernels/cuda/glm53_exl3_linear.cu        linear.cu's device part, its anonymous namespace named tf_exl3_linear
                                               (kernels need a stable symbol), plus the explicit instantiations below
* zig/kernels/cuda/glm53_exl3_experts.cu       experts.cu's device kernels (namespace tf_exl3x_k) plus the grouped
                                               kernel instantiations GLM-5.3's decode windows launch

Only text moves: every kernel body is the Python build's, so tests/cuda/nemotron/sass_compare.py-style checks against
the Python extension's .cuda.o can prove the SASS. ``--check`` compares instead of writing (exit 1 on drift).
Usage: python3 -B tools/glm53/copy_exl3_kernels.py --src <champion src>/src/tensorfold/cuda/exl3 [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "zig" / "kernels" / "cuda"

# linear_kernel<K2, CB, WK, G, V>: GLM-5.3's dense linears are 5-bit mul1 (K2 10, CB 2); the 2.75 bpw mixed-K pack
# also has 3/4-bit (K2 6/8) dense parts in other packs. WK from x3linear.plan (4 or 8), G 1 (<= 8 rows) or 2, V = vec_ok.
LINEAR_K2 = (6, 8, 10)
LINEAR_CB = (2,)
# grouped_kernel<CB, NT, W, PF, V, LO, HI> with GLM's tiles (8 n tiles, 4 warps), 16-byte loads (V 1, PF 1) and every
# K2 range the launcher picks
EXPERT_RANGES = ((8, 8), (2, 10), (2, 16))


def vec_ok(k2: int) -> int:
    return int(not (k2 in (2, 4)) and k2 <= 12)


def strip_includes(lines: list[str]) -> list[str]:
    """ATen / c10 includes cut; <cstdint> added (torch's headers brought uint32_t / int64_t in transitively)."""
    kept = [ln for ln in lines if not ln.startswith(("#include <ATen", "#include <c10"))]
    return (["#include <cstdint>"] if "#include <cstdint>" not in kept else []) + kept


def linear_cu(src: str) -> str:
    lines = strip_includes(src.splitlines())
    out, named = [], False
    for ln in lines:
        if ln.startswith("int dtype_of(const at::Tensor& t)"):
            break
        if ln == '#include "decode.cuh"':
            ln = '#include "glm53/decode.cuh"'
        if ln == "namespace {" and not named:
            ln, named = "namespace tf_exl3_linear {", True
        out.append(ln)
    else:
        raise SystemExit("linear.cu: the host part's first line (dtype_of) was not found")
    if not named:
        raise SystemExit("linear.cu: no anonymous namespace")
    head = ["// Device code of src/tensorfold/cuda/exl3/linear.cu (up to dtype_of; ATen includes and the host launchers "
            "dropped,", "// the anonymous namespace named), generated by tools/glm53/copy_exl3_kernels.py: do not edit.",
            ""]
    inst = ["}  // namespace tf_exl3_linear", "",
            "// rot_in_kernel and the linear_kernel instantiations GLM-5.3's dense EXL3 linears launch (loads 35:",
            "// transposed walk, 16-byte weight loads where vec_ok, PDL).",
            "template __global__ void tf_exl3_linear::linear_kernel<%d, %d, %d, %d, %d>(const __grid_constant__ "
            "tf_exl3_linear::Jobs, int, int);"]
    lines_inst = []
    for k2 in LINEAR_K2:
        for cb in LINEAR_CB:
            for wk in (4, 8):
                for g in (1, 2):
                    lines_inst.append(inst[-1] % (k2, cb, wk, g, vec_ok(k2)))
    return "\n".join(head + out + inst[:-1] + lines_inst) + "\n"


def grouped_cuh(src: str) -> str:
    lines = strip_includes(src.splitlines())
    out, skip = [], False
    i = 0
    while i < len(lines):
        ln = lines[i]
        # launch_ex: a host template (cudaLaunchKernelEx + C10_CUDA_CHECK) up to its closing brace
        if ln.startswith("template <typename... KArgs, typename... Args>"):
            j = i
            while lines[j] != "}":
                j += 1
            i = j + 1
            continue
        # struct GroupedArgs and the host launchers after it: everything up to the namespace's end
        if ln.startswith("struct GroupedArgs {"):
            skip = True
        if skip and ln.startswith("}  // namespace tf_exl3x"):
            skip = False
        if not skip:
            out.append(ln)
        i += 1
    if "launch_ex" in "\n".join(out) or "TORCH_CHECK" in "\n".join(out):
        raise SystemExit("experts_grouped.cuh: host code left in the device copy")
    head = ["// Device part of src/tensorfold/cuda/exl3/experts_grouped.cuh (ATen includes, launch_ex, GroupedArgs and "
            "the host", "// launchers dropped), generated by tools/glm53/copy_exl3_kernels.py: do not edit."]
    return "\n".join(head + out) + "\n"


def experts_cu(src: str) -> str:
    lines = strip_includes(src.splitlines())
    out, named = [], False
    for ln in lines:
        if ln.startswith("// ----------------------------------------"):
            break
        if ln == "using tf_exl3x::launch_ex;":           # a host template, not in the device copy
            continue
        if ln == '#include "experts_grouped.cuh"':
            ln = '#include "glm53/experts_grouped.cuh"'
        if ln == "namespace {" and not named:
            ln, named = "namespace tf_exl3x_k {", True
        out.append(ln)
    else:
        raise SystemExit("experts.cu: the host part's separator was not found")
    while out and out[-1].strip() == "":
        out.pop()
    if not out or not out[-1].startswith("}  // namespace"):
        raise SystemExit("experts.cu: the device part does not end with its namespace")
    out[-1] = "}  // namespace tf_exl3x_k"
    head = ["// Device kernels of src/tensorfold/cuda/exl3/experts.cu (ATen includes and host launchers dropped, the "
            "anonymous", "// namespace named) and the grouped kernels of experts_grouped.cuh GLM-5.3's decode windows "
            "launch,", "// generated by tools/glm53/copy_exl3_kernels.py: do not edit.", ""]
    inst = ["", "// GLM's expert tiles (8 n tiles, 4 warps), 16-byte trellis loads one k step ahead (TF_EXL3_EXPERTS_LOADS 1),",
            "// mul1 (codebook 2), every K2 range grouped_launch picks."]
    for lo, hi in EXPERT_RANGES:
        inst.append(f"template __global__ void tf_exl3x::grouped_kernel<2, 8, 4, 1, 1, {lo}, {hi}>(const half*, "
                    "const half*, const int64_t*, const int64_t*, const int*, const int*, const int*, const int*, "
                    "const int*, float*, int, int, int, int, int, int, int, const tf_exl3x::Epi);")
    inst.append("template __global__ void tf_exl3x_k::rot_in_kernel<__nv_bfloat16>(const __nv_bfloat16*, int, "
                "const int*, const half*, const half*, half*, half*, int, int, int);")
    return "\n".join(head + out + inst) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True, help="the Python engine's src/tensorfold/cuda/exl3")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    src = Path(a.src)
    files = {
        OUT / "glm53" / "decode.cuh": (src / "decode.cuh").read_text(),
        OUT / "glm53" / "experts_grouped.cuh": grouped_cuh((src / "experts_grouped.cuh").read_text()),
        OUT / "glm53_exl3_linear.cu": linear_cu((src / "linear.cu").read_text()),
        OUT / "glm53_exl3_experts.cu": experts_cu((src / "experts.cu").read_text()),
    }
    bad = 0
    for path, text in files.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                print(f"DRIFT {path.relative_to(REPO)}")
                bad = 1
            else:
                print(f"same  {path.relative_to(REPO)}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO)} ({text.count(chr(10))} lines)")
    return bad


if __name__ == "__main__":
    sys.exit(main())
